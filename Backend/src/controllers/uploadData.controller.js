import finalReportModel from "../models/finalReportModel.js";
import generateFinalReport from "../services/ai.service.js";
import { createRequire } from "module"; //pdf-parse does not support standard import syntax in modern Node.js.
const require = createRequire(import.meta.url);
const pdfparse = require("pdf-parse");

export async function uploadData(req, res) {
  //upload.single("resume") reads the binary data, processes the file,and automatically creates a new property on Express's request object called req.file.
 const resumeContent = (
  await new pdfparse.PDFParse(Uint8Array.from(req.file.buffer)).getText()
).text;
  const { selfDescription, jobDescription } = req.body;

  const finalReportByAi = await generateFinalReport({
    resume: resumeContent,
    selfDescription,
    jobDescription,
  });

  const FinalReport = await finalReportModel.create({
    user: req.user.id,
    resume: resumeContent,
    selfDescription,
    jobDescription,
    ...finalReportByAi, //Spread Operator that takes all the key-value pairs generated by your AI model inside interViewReportByAi
  });

  res.status(201).json({
    message: "Final Report Generated Successfully",
    FinalReport,
  });
}
